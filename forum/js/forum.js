  var WHY = ['politics', 'slur', 'nsfw', 'violence', 'spam', 'link', 'reports'];
  function whyText(item) {
    if (!item || item.status === 'published') return '';
    var r = String(item.mod_reason || '').toLowerCase();
    var code = r.replace(/^(auto|bot|admin|ai)\s*:\s*/, '').split(/[\s:,.]/)[0];
    if (WHY.indexOf(code) >= 0) return t('f.why.' + code);
    if (item.status === 'rejected') return t('f.why.other');
    return '';
  }
  function errText(err, ctx) {
    var m = String((err && (err.message || err.error_description || err.msg)) || err || '');
    var keys = ['rate_limit_posts', 'rate_limit_comments', 'rate_limit_reports', 'not_signed_in', 'display_name_not_allowed', 'post_not_open'];
    for (var i = 0; i < keys.length; i++) if (m.indexOf(keys[i]) >= 0) return t('f.err.' + keys[i]);
    if (err && err.code === '23505') return ctx === 'report' ? t('f.already_reported') : ctx === 'name' ? t('f.err.name_taken') : t('f.err.generic');
    if (/invalid login|email not confirmed/i.test(m)) return t('f.auth.bad_login');
    if (window.console) console.warn('forum:', err);
    return t('f.err.generic');
  }

